def _web(domain: int, *url_substrs: str) -> list[dict]:
    """Pick web_sources for a question by URL substring match."""
    domain_sources = WEB["domains"][str(domain)]["sources"]
    picks = []
    for needle in url_substrs:
        for s in domain_sources:
            if needle in s["url"]:
                picks.append({"url": s["url"], "title": s["title"], "captured": s["captured"]})
                break
    return picks


def Q(qid, domain, subdomain, difficulty, stem, choices, correct, explanation,
      source="canonical", guide_pages=None, guide_section=None,
      web_url_keys=None, references=None, tags=None, notes=""):
    return {
        "id": qid,
        "domain": domain,
        "subdomain": subdomain,
        "difficulty": difficulty,
        "stem": stem,
        "choices": list(choices),
        "correct": correct,
        "explanation": explanation,
        "source": source,
        "guide_pages": guide_pages or [],
        "guide_section": guide_section or "",
        "web_sources": _web(domain, *(web_url_keys or [])),
        "references": references or [],
        "tags": tags or [],
        "notes": notes,
    }


